    public sealed partial class AirtistLandscapePrototypeController
    {
        private static ChapterData[] WithLouvreExpansion(ChapterData[] original) => original.Concat(
            AirtistLouvreExpansion.Levels.Select(level => new ChapterData(level.title,
                $"Найди AI-дорисовки: {level.targets.Length}", "Все добавленные детали найдены. Картина готова пополнить коллекцию.",
                level.fact, level.targets[0].hint, level.targets.Select(target => new ArtifactData(target.name,
                    target.hint,target.point,new Vector2(72,64),ArtifactVisual.Badge)).ToArray()))).ToArray();

        private static string[] WithLouvreIds(string[] original) => original.Concat(AirtistLouvreExpansion.Levels.Select(l=>l.id)).ToArray();
        public static int PaintingCount => Chapters.Length;
        public static int TotalHiddenObjectCount => Chapters.Sum(c=>c.Artifacts.Length);
        public static string RouteSummary => $"{PaintingCount} картин · {TotalHiddenObjectCount} AI-следов · 1 коллекция";
    }
